/// 13 只兽灵中破御 / 破胆 / 冰精 / 火灵 / 毒蛊 / 玄兽 / 迟钝 / 狡猾 / 憨厚 /
/// 拼命共 10 只已收录 7 阶完整数据（来源：小程序「TLBB怀旧攻略 · 兽灵被动技能」，
/// 用户核验），痛击 / 连击 / 灵动逐阶数值待补，仅收录攻略共识。
///
/// 文案中的 `<b>…</b>`（金强调）与 `<i>…</i>`（未解锁占位）由表现层解析。
library;

import 'package:flutter/foundation.dart';

/// 兽灵数据完整度（对应原型标题行右侧 tag）。
enum BeastSpiritStatus {
  /// 已收录 7 阶逐阶数据（`.tag-gold`）。
  complete('完整数据'),

  /// 逐阶数值待补，仅收录攻略共识（`.tag`）。
  pending('待补');

  const BeastSpiritStatus(this.label);

  /// tag 文案。
  final String label;
}

/// 兽灵技能类型（对应小程序顶部「兽灵被动技能 / 兽灵手动技能」两个页签）。
enum BeastSpiritKind {
  /// 被动技能（当前收录的全部兽灵均属此类）。
  passive('被动技能'),

  /// 手动技能（小程序「兽灵手动技能」页签，数据待补）。
  manual('手动技能');

  const BeastSpiritKind(this.label);

  /// 筛选 chip / 文案。
  final String label;
}

/// 单个阶位的兽灵效果。
@immutable
class BeastSpiritTier {
  const BeastSpiritTier({
    required this.name,
    required this.lv,
    required this.dec,
    required this.effect1,
    required this.effect2,
  });

  /// 阶位名（如 `一阶`）。
  final String name;

  /// 等级区间（如 `1-3 级`）。
  final String lv;

  /// 阶位说明（含 `<b>…</b>` 金强调）。
  final String dec;

  /// 兽灵效果一（4 级解锁；含 `<b>…</b>` / `<i>…</i>`）。
  final String effect1;

  /// 兽灵效果二（10 级解锁；含 `<b>…</b>` / `<i>…</i>`）。
  final String effect2;
}

/// 一只兽灵（以珍兽技能为单位）。
@immutable
class BeastSpirit {
  const BeastSpirit({
    required this.id,
    required this.name,
    required this.sub,
    required this.status,
    this.kind = BeastSpiritKind.passive,
    this.tiers = const [],
    this.pendingBody = '',
    this.pendingNote = '',
  });

  /// 稳定 id（对应原型 `#poyu` / `#podan` / …）。
  final String id;

  /// 名称（如 `破御` / `冰精`，即小程序里的技能名，不带「兽灵」后缀）。
  final String name;

  /// 一句话定位（如 `破防 · 会心削减`）。
  final String sub;

  /// 数据完整度。
  final BeastSpiritStatus status;

  /// 技能类型（被动 / 手动），对应小程序两个页签。
  final BeastSpiritKind kind;

  /// 7 阶数据；[status] 为 [BeastSpiritStatus.pending] 时为空。
  final List<BeastSpiritTier> tiers;

  /// 待补正文（含 `<b>…</b>`）；仅 [BeastSpiritStatus.pending] 使用。
  final String pendingBody;

  /// 待补攻略注（`※` 起头，走 `.soul-fx` 样式）；仅待补兽灵使用。
  final String pendingNote;

  /// 是否已收录 7 阶完整数据。
  bool get isComplete => status == BeastSpiritStatus.complete;
}

